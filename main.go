func initGame() {
	game = Game{
		Health:    100,
		MaxHealth: 100,
		Ammo:      50,
		MaxAmmo:   100,
		Weapon:    WeaponPistol,
		Level:     0,
		DoorOpen:  make(map[[2]int]bool),
		LastTick:  time.Now(),
	}

	loadLevel(0)
	spawnEntities()
}

func loadLevel(idx int) {
	if idx >= len(maps) {
		game.Won = true
		return
	}

	m := maps[idx]
	game.Map = m.wall
	game.MapObjects = m.objects
	game.PlayerX = m.px
	game.PlayerY = m.py
	game.PlayerAngle = m.pa
	game.Level = idx
	game.Entities = nil
	game.BloodSpots = nil
	game.DoorOpen = make(map[[2]int]bool)

	spawnEntities()
}

func spawnEntities() {
	// Spawn enemies based on level
	enemyTypes := []int{EntityDemon, EntityImp, EntityZombie}
	enemyHealth := []int{30, 20, 10}
	enemySprites := []rune{'悪', '鬼', '屍'}

	for i := 0; i < 8+game.Level*4; i++ {
		x, y := findEmptySpot()
		etype := i % len(enemyTypes)
		game.Entities = append(game.Entities, Entity{
			X:       x,
			Y:       y,
			Type:    enemyTypes[etype],
			Health:  enemyHealth[etype],
			Alive:   true,
			Speed:   0.02 + float64(game.Level)*0.005,
			Sprite:  enemySprites[etype],
			Color:   ColorBrightRed,
		})
	}

	// Spawn items
	itemTypes := []int{EntityHealth, EntityAmmo, EntityKey}
	for i := 0; i < 4+game.Level*2; i++ {
		x, y := findEmptySpot()
		game.Entities = append(game.Entities, Entity{
			X:     x,
			Y:     y,
			Type:  itemTypes[i%len(itemTypes)],
			Alive: true,
		})
	}

	// Spawn barrels
	for i := 0; i < 3; i++ {
		x, y := findEmptySpot()
		game.Entities = append(game.Entities, Entity{
			X:     x,
			Y:     y,
			Type:  EntityBarrel,
			Alive: true,
		})
	}
}

func findEmptySpot() (float64, float64) {
	for {
		x := float64(2 + (game.Frame * 7 % 20))
		y := float64(2 + (game.Frame * 13 % 20))
		game.Frame++
		if x >= 1 && x < MapWidth-1 && y >= 1 && y < MapHeight-1 &&
			game.Map[int(y)][int(x)] == WallEmpty {
			return x, y
		}
	}
}
